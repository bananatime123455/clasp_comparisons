_UNIT_DIR = Path(__file__).parent.resolve()


class UNITPipeline:
    def __init__(
        self,
        train_files: list,
        test_files:  list,
        val_files:   list,
        modality_1:  str,
        modality_2:  str,
        batch_size:  int   = 1,
        buffer_size: int   = 0,
        epochs:      int   = 1,
        early_stopping_patience: int   = 10,
        early_stopping_delta:    float = 0.0,
        num_workers: int   = 4,
        image_size:  int   = 256,
        logdir:      str   = None,
    ):
        self.train_files = [Path(p) for p in train_files]
        self.test_files  = [Path(p) for p in test_files]
        self.val_files   = [Path(p) for p in val_files]
        self.modality_1  = modality_1
        self.modality_2  = modality_2
        self.batch_size  = batch_size
        self.epochs      = epochs
        self.num_workers = num_workers
        self.image_size  = image_size

        self.logdir = Path(logdir).resolve() if logdir else (
            _UNIT_DIR.parent.parent / "logs" / f"unit_{modality_1}_vs_{modality_2}"
        ).resolve()
        self.logdir.mkdir(parents=True, exist_ok=True)
        self.config_path = self.logdir / "unit_mri.yaml"

    def train(self) -> dict:
        steps = tqdm(
            total=4,
            desc="[UNITPipeline] Overall progress",
            unit="step",
            position=0,
            leave=True,
        )

        steps.set_description("[UNITPipeline] Writing config")
        self._write_config()
        steps.update(1)

        steps.set_description("[UNITPipeline] Training")
        epochs_trained = self._run_training()
        steps.update(1)

        steps.set_description("[UNITPipeline] Running inference")
        self._run_inference()
        steps.update(1)

        steps.set_description("[UNITPipeline] Computing metrics")
        ssim_vals, psnr_vals, mse_vals = self._compute_metrics()
        steps.update(1)
        steps.set_description("[UNITPipeline] Done")
        steps.close()

        results = {
            "model":          "UNIT",
            "modality_1":     self.modality_1,
            "modality_2":     self.modality_2,
            "epochs_trained": epochs_trained,
            "ssim": float(np.mean(ssim_vals)),
            "psnr": float(np.mean(psnr_vals)),
            "mse":  float(np.mean(mse_vals)),
        }

        out = self.logdir / "unit_results.json"
        out.write_text(json.dumps(results, indent=2))
        tqdm.write(f"[UNITPipeline] Results saved → {out}")
        return results

