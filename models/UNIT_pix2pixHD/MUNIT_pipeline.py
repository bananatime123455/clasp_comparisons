import sys
import subprocess
from pathlib import Path
from typing import Optional

from data_processing import resolve_h5_key
from tqdm import tqdm

from UNIT_pipeline import UNITPipeline

_MUNIT_DIR = Path(__file__).parent.resolve()


class MUNITPipeline(UNITPipeline):
    """
    Reuses UNITPipeline's train()/metrics plumbing (and, notably, its
    _run_training(), since MUNIT consumes the exact same H5 file-list /
    images_a+images_b format as UNIT — no train_h5_munit.py or
    get_h5_dataloaders_munit.py needed, unlike pix2pixHD which required
    its own loader/dataset because of its label+image data format).

    Only _write_config() (MUNIT's model/trainer hyperparameters) and
    _run_inference() (MUNIT has its own evaluate_h5_munit.py, because its
    generator's forward pass / output dict differs from UNIT's) are
    overridden.

    MUNIT trains two full encoder/decoder branches (domain A and B) and
    runs its discriminators in both translation directions every step,
    so at identical batch_size/image_size it needs noticeably more GPU
    memory than UNIT. By default this scales batch_size down for MUNIT
    specifically so a comparison run configured for UNIT doesn't OOM on
    MUNIT; pass munit_batch_size_scale=1.0 to force the same batch_size
    as every other model (e.g. once you've confirmed it fits).
    """

    def __init__(self, *args, munit_batch_size_scale: float = 0.5, **kwargs):
        super().__init__(*args, **kwargs)
        if munit_batch_size_scale != 1.0:
            scaled = max(1, int(self.batch_size * munit_batch_size_scale))
            if scaled != self.batch_size:
                tqdm.write(
                    f"[MUNITPipeline] Scaling batch_size {self.batch_size} -> "
                    f"{scaled} (munit_batch_size_scale={munit_batch_size_scale}) "
                    "since MUNIT is more memory-hungry than UNIT at the same "
                    "batch size. Pass munit_batch_size_scale=1.0 to disable."
                )
            self.batch_size = scaled

    # ------------------------------------------------------------------
    # Step 1 — write YAML config + file lists (train/val/test)
    # ------------------------------------------------------------------

    def _write_config(self):
        sz       = self.image_size
        max_iter = self.epochs * 10
        h5_key_1 = resolve_h5_key(self.modality_1)
        h5_key_2 = resolve_h5_key(self.modality_2)

        train_list = self.logdir / "train_files.txt"
        val_list   = self.logdir / "val_files.txt"
        test_list  = self.logdir / "test_files.txt"

        for list_path, files, label in (
            (train_list, self.train_files, "train"),
            (val_list,   self.val_files,   "val"),
            (test_list,  self.test_files,  "test"),
        ):
            lines = [
                str(Path(p).resolve())
                for p in tqdm(
                    files,
                    desc=f"[MUNITPipeline]   writing {label} file list",
                    unit="file",
                    position=1,
                    leave=False,
                )
            ]
            list_path.write_text("\n".join(lines))

        # Hyperparameters below mirror imaginaire's stock MUNIT configs
        # (configs/projects/munit/*/ampO1.yaml) — spectral-norm "improved"
        # MUNIT variant, TTUR (dis lr 4x gen lr), hinge loss.
        yaml_str = f"""# Auto-generated by MUNITPipeline
image_display_iter: 10
image_save_iter: 5
snapshot_save_iter: 100
max_iter: {max_iter}
logging_iter: 1

trainer:
    strict_resume: False
    type: imaginaire.trainers.munit
    model_average_config:
        enabled: True
    amp_config:
        enabled: True
    gan_mode: hinge
    perceptual_mode: vgg19
    perceptual_layers: relu_4_1
    loss_weight:
        gan: 1
        image_recon: 1
        content_recon: 1
        style_recon: 1
        perceptual: 0
        cycle_recon: 1
        gp: 0
        consistency_reg: 0
    init:
        type: orthogonal
        gain: 1

gen_opt:
    type: adam
    lr: 0.0001
    adam_beta1: 0.5
    adam_beta2: 0.999
    lr_policy:
        type: constant

dis_opt:
    type: adam
    lr: 0.0004
    adam_beta1: 0.5
    adam_beta2: 0.999
    lr_policy:
        type: constant

gen:
    type: imaginaire.generators.munit
    latent_dim: 8
    num_filters: 64
    num_filters_mlp: 256
    num_res_blocks: 4
    num_mlp_blocks: 2
    num_downsamples_style: 4
    num_downsamples_content: 2
    content_norm_type: instance
    style_norm_type: none
    decoder_norm_type: instance
    weight_norm_type: spectral
    pre_act: True

dis:
    type: imaginaire.discriminators.munit
    patch_wise: False
    num_filters: 32
    max_num_filters: 512
    num_layers: 6
    activation_norm_type: none
    weight_norm_type: spectral

# MUNIT is many-to-many: at test time it needs to know which direction to
# translate, and whether to sample a random style code or use the style
# encoded from an example image in the target domain. random_style: False
# gives deterministic, comparable metrics against a fixed ground-truth b.
inference_args:
    a2b: True
    random_style: False

data:
    name: brats_mri_munit
    type: imaginaire.datasets.h5_mri
    modality_a: '{h5_key_1}'
    modality_b: '{h5_key_2}'
    modality_a_display: '{self.modality_1}'
    modality_b_display: '{self.modality_2}'
    train_file_list: '{train_list}'
    val_file_list: '{val_list}'
    test_file_list: '{test_list}'
    num_workers: {self.num_workers}
    input_types:
        - images_a:
            ext: ~
            num_channels: 3
            normalize: True
        - images_b:
            ext: ~
            num_channels: 3
            normalize: True
    train:
        roots:
            - '{self.logdir}'
        batch_size: {self.batch_size}
        augmentations:
            resize_smallest_side: {sz}
            random_scale_limit: 0.1
            horizontal_flip: True
            random_crop_h_w: {sz}, {sz}
    test:
        roots:
            - '{self.logdir}'
        batch_size: 1
        augmentations:
            resize_smallest_side: {sz}
            center_crop_h_w: {sz}, {sz}
    val:
        roots:
            - '{self.logdir}'
        batch_size: 1
        augmentations:
            resize_smallest_side: {sz}
            center_crop_h_w: {sz}, {sz}

test_data:
    type: imaginaire.datasets.h5_mri
    input_types:
        - images_a:
              ext: ~
              num_channels: 3
              normalize: True
        - images_b:
              ext: ~
              num_channels: 3
              normalize: True
    paired: True
    test:
        is_lmdb: False
        roots:
            - '{self.logdir}'
        batch_size: 1
        augmentations:
            resize_smallest_side: {sz}
            center_crop_h_w: {sz}, {sz}"""

        self.config_path.write_text(yaml_str.strip())
        tqdm.write(f"[MUNITPipeline] Config → {self.config_path}")

    # ------------------------------------------------------------------
    # Step 2 — train
    # ------------------------------------------------------------------
    # Reuses UNITPipeline._run_training()'s command (`train_h5.py` is
    # generic — it patches imaginaire's dataloader with
    # get_h5_dataloaders.py and reads train_file_list/val_file_list from
    # the config, same fields MUNIT's config above writes out), but adds
    # expandable_segments to the child process's allocator config since
    # MUNIT's dual-branch memory usage fragments more than UNIT's.

    def _run_training(self) -> int:
        import os
        env = os.environ.copy()
        existing = env.get("PYTORCH_CUDA_ALLOC_CONF", "")
        if "expandable_segments" not in existing:
            env["PYTORCH_CUDA_ALLOC_CONF"] = (
                (existing + ",") if existing else ""
            ) + "expandable_segments:True"

        train_cmd = [
            sys.executable, "-m", "torch.distributed.run",
            "--nproc_per_node=1",
            "train_h5.py",
            "--config", str(self.config_path.resolve()),
            "--logdir", str(self.logdir.resolve()),
            "--single_gpu",
            "--early_stopping_patience", str(self.early_stopping_patience),
            "--early_stopping_delta", str(self.early_stopping_delta),
        ]
        tqdm.write(f"[MUNITPipeline] Inner command:\n  {' '.join(train_cmd)}")
        result = subprocess.run(train_cmd, cwd=str(_MUNIT_DIR), env=env, check=False)
        if result.returncode != 0:
            raise RuntimeError(
                f"[MUNITPipeline] Training failed (exit {result.returncode})."
            )
        return self._parse_last_iteration()

    # ------------------------------------------------------------------
    # Step 3 — inference
    # ------------------------------------------------------------------

    def _run_inference(self):
        self.inference_dir = self.logdir / "inference"
        self.inference_dir.mkdir(parents=True, exist_ok=True)

        checkpoint = self._find_latest_checkpoint()
        if checkpoint is None:
            tqdm.write("[MUNITPipeline] No checkpoint found — skipping inference.")
            return

        val_list = self.logdir / "val_files.txt"

        infer_cmd = [
            sys.executable, "evaluate_h5_munit.py",
            "--config", str(self.config_path),
            "--checkpoint", str(checkpoint),
            "--file_list", str(val_list),
            "--output_dir", str(self.inference_dir),
            "--single_gpu",
        ]
        tqdm.write(f"[MUNITPipeline] Inner command:\n  {' '.join(infer_cmd)}")
        result = subprocess.run(infer_cmd, cwd=str(_MUNIT_DIR), check=False)
        if result.returncode != 0:
            tqdm.write(f"[MUNITPipeline] Inference exit {result.returncode}.")