    def _run_training(self) -> int:
        cmd = [sys.executable, "-m", "torch.distributed.run", "--nproc_per_node=1",
               "train_h5_p2p.py", "--config", str(self.config_path.resolve()),
               "--logdir", str(self.logdir.resolve()), "--single_gpu"]
        import subprocess
        result = subprocess.run(cmd, cwd=str(_P2P_DIR), check=False)
        if result.returncode != 0:
            raise RuntimeError(f"pix2pixHD training failed (exit {result.returncode}).")
        return self._parse_last_iteration()

    def _run_inference(self):
        self.inference_dir = self.logdir / "inference"
        self.inference_dir.mkdir(parents=True, exist_ok=True)
        checkpoint = self._find_latest_checkpoint()
        if checkpoint is None:
            tqdm.write("[Pix2PixHDPipeline] No checkpoint found — skipping inference.")
            return
        val_list = self.logdir / "val_files.txt"
        cmd = [sys.executable, "evaluate_h5_p2p.py", "--config", str(self.config_path),
            "--checkpoint", str(checkpoint), "--file_list", str(val_list),
            "--output_dir", str(self.inference_dir), "--single_gpu"]
        tqdm.write(f"[Pix2PixHDPipeline] Inner command:\n  {' '.join(cmd)}")
        result = subprocess.run(cmd, cwd=str(_P2P_DIR), check=False)
        if result.returncode != 0:
            raise RuntimeError(f"pix2pixHD inference failed (exit {result.returncode}).")